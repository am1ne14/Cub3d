#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int			i;
	int			sign;
	int			result;
	const char	*str;

	sign = 1;
	i = 0;
	result = 0;
	str = nptr;
	while (str[i] == ' ' || (9 <= str[i] && str[i] <= 13))
		i++;
	if (str[i] == '-' || str[i] == '+')
	{
		if (str[i] == '-')
			sign = sign * -1;
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		result = result * 10 + (str[i] - '0');
		i++;
	}
	return (result * sign);
}
